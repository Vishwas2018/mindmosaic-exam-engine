#!/usr/bin/env node
/**
 * Builds the owner attestation packet for the 77 NAPLAN numeracy approvals recorded on 2026-11-13 from a chat
 * statement (CONTENT-GOVERNANCE.md). It reads content/publication-approvals/*.json and writes a checklist the owner
 * can work through and sign. It records nothing and changes no approval: the packet is evidence of what was
 * attested to, and only the owner can complete it.
 *
 *   node scripts/beta/build-attestation-packet.mjs   # writes docs/beta-readiness/OWNER-ATTESTATION-77.md
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const DIR = "content/publication-approvals";
const OUT = "docs/beta-readiness/OWNER-ATTESTATION-77.md";
const BATCH = "2026-11-13T10:57:49.837Z";

const records = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8")))
  .filter((r) => r.approvedAt === BATCH)
  .sort(
    (a, b) =>
      a.question.yearLevel - b.question.yearLevel ||
      a.questionId.localeCompare(b.questionId),
  );

const one = (s) =>
  String(s ?? "")
    .replace(/\s+/g, " ")
    .replace(/\|/g, "\\|")
    .trim();

/** The visible text of an option/label/target id anywhere in the item, so the reviewer sees words, not ids. */
function textOf(q, id) {
  let found;
  const walk = (v) => {
    if (found !== undefined || v === null || typeof v !== "object") return;
    if (Array.isArray(v)) return v.forEach(walk);
    if (v.id === id && (v.text ?? v.label) !== undefined) {
      found = v.text ?? v.label;
      return;
    }
    Object.values(v).forEach(walk);
  };
  walk([q.options, q.interaction]);
  return found === undefined ? id : one(found);
}

function answer(q) {
  const k = q.answerKey ?? {};
  switch (k.kind) {
    case "single_option":
      return textOf(q, k.optionId);
    case "multiple_options":
    case "ordering":
      return (k.optionIds ?? [])
        .map((id) => textOf(q, id))
        .join(k.kind === "ordering" ? " → " : "; ");
    case "fill_blank":
      return (k.blanks ?? [])
        .map((b) => (b.acceptedAnswers ?? []).join(" / "))
        .join(" ; ");
    case "number":
      return `${k.value}${k.unit ? ` ${k.unit}` : ""}${k.tolerance ? ` (±${k.tolerance})` : ""}`;
    case "boolean":
      return k.value ? "True" : "False";
    case "matching":
      return (k.pairs ?? [])
        .map((p) => `${textOf(q, p.sourceId)} → ${textOf(q, p.targetId)}`)
        .join("; ");
    case "dropdown":
      return (k.fields ?? [])
        .map((f) => `${textOf(q, f.id)}: ${textOf(q, f.correctOptionId)}`)
        .join("; ");
    default: {
      const rest = { ...k };
      delete rest.caseSensitive;
      delete rest.trimWhitespace;
      return one(JSON.stringify(rest));
    }
  }
}

if (records.length !== 77) {
  console.error(
    `expected 77 records in batch ${BATCH}, found ${records.length}`,
  );
  process.exit(1);
}
const byYear = (y) => records.filter((r) => r.question.yearLevel === y).length;
const listHash = crypto
  .createHash("sha256")
  .update(records.map((r) => `${r.questionId}:${r.contentHash}`).join("\n"))
  .digest("hex");

const rows = records.map(
  (r, i) =>
    `| ${i + 1} | \`${r.questionId}\` | Y${r.question.yearLevel} | ${one(r.question.metadata?.topic)} | ` +
    `${one(r.question.prompt)} | ${answer(r.question)} | \`${r.contentHash.slice(0, 12)}\` | [ ] |`,
);

const md = `# Owner attestation: 77 NAPLAN-style numeracy items

Generated by \`scripts/beta/build-attestation-packet.mjs\` from \`content/publication-approvals/\`. **Not signed.**

## Why this exists

The 77 approvals (${byYear(3)} Year 3, ${byYear(5)} Year 5) were recorded on ${BATCH} from the owner's chat statement
that all 78 family-beta items had been reviewed. They share one timestamp and one reviewer, and the repository holds
no per-item review evidence (CONTENT-GOVERNANCE.md). This packet turns that statement into a checkable record.
Y5 Q20 (\`man-eb2d2e6d5ddfebf6c5085c6e\`) is **not** in this list: it has no approval and stays excluded.

Nothing in this file approves anything. Approvals stay exactly as recorded; if an item fails review, its approval
file is deleted and the deployed gate stops serving it.

## How to complete it

1. For each row, open the item (locally: \`MM_PUBLICATION_GATE=report npm run dev\`, then the Year 3 or Year 5
   practice route) and check: the answer in the table is correct, the wording and any picture are unambiguous, and
   it suits the year level.
2. Tick the last column, or write the problem next to the id.
3. Sign the statement at the end (name, date) and commit the file, or reply in PR #124 quoting the statement.

The item list fingerprint (\`sha256\` of \`id:contentHash\` lines) is \`${listHash}\`. If an item's content changes
its hash changes, and its approval stops validating, so the attestation covers exactly these versions.

| # | Item | Year | Topic | Prompt | Accepted answer | Content hash | Reviewed |
|--:|------|------|-------|--------|-----------------|--------------|:--------:|
${rows.join("\n")}

## Statement (owner to complete)

> I reviewed each of the 77 items listed above, at the content hashes shown, for correctness of the answer,
> clarity of wording and pictures, originality, and suitability for the year level. Items I did not tick are
> listed below and must be withdrawn.
>
> Items to withdraw: ____________________
>
> Name: ____________________  Date: ____________________
`;

fs.writeFileSync(OUT, md);
console.log(
  `wrote ${OUT}: ${records.length} items (Y3 ${byYear(3)}, Y5 ${byYear(5)}), list sha256 ${listHash}`,
);
